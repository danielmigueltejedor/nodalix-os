export function translateLabel(label) {
 if (typeof label !== 'string') return label;
 if (Object.hasOwn(LABELS, label)) return LABELS[label];
 const suffix = label.match(/(…|\.\.\.| ✓)$/)?.[0] ?? '';
 if (suffix) {
  const base = label.slice(0, -suffix.length);
  const translated = translateLabel(base);
  if (translated !== base) return translated + suffix;
 }
 let match = label.match(/^Switch to Tab (\d+)$/);
 if (match) return `Ir a la pestaña ${match[1]}`;
 match = label.match(/^Tab (\d+)$/);
 if (match) return `Pestaña ${match[1]}`;
 match = label.match(/^Move to (Workspace|Monitor) (Left|Right|Up|Down)$/);
 if (match) {
  const directions = {Left:'a la izquierda',Right:'a la derecha',Up:'arriba',Down:'abajo'};
  return `Mover al ${match[1] === 'Workspace' ? 'espacio de trabajo' : 'monitor'} ${directions[match[2]]}`;
 }
 match = label.match(/^About (.+)$/);
 if (match) return `Acerca de ${match[1]}`;
 return label;
}
